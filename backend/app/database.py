"""Prediction persistence backed by PostgreSQL or local SQLite."""
from datetime import datetime, timezone
from pathlib import Path

from backend.app.config import get_settings
from mlops.data.connection import connect_database

DEFAULT_DB_PATH = Path(__file__).resolve().parents[2] / "mlops" / "data" / "predictions.db"
_SETTINGS = get_settings()
DB_URL = _SETTINGS.database_url
DB_PATH = _SETTINGS.database_path
DB_DIR = DB_PATH.parent


def get_database_target():
    return DB_URL if DB_URL else DB_PATH


def get_connection():
    """Return the selected backend connection context; never silently fallback."""
    return connect_database(get_database_target())


def check_database_connection():
    with connect_database(get_database_target(), readonly=True) as conn:
        conn.execute("SELECT 1").fetchone()


def initialize_database(target=None):
    target = target if target is not None else get_database_target()
    with connect_database(target) as conn:
        if conn.postgres:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    timestamp TEXT NOT NULL,
                    url TEXT NOT NULL,
                    prediction TEXT NOT NULL,
                    confidence DOUBLE PRECISION NOT NULL,
                    model_version TEXT NOT NULL,
                    feedback TEXT,
                    feedback_timestamp TEXT
                )
            """)
        else:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS predictions (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    timestamp TEXT NOT NULL,
                    url TEXT NOT NULL,
                    prediction TEXT NOT NULL,
                    confidence REAL NOT NULL,
                    model_version TEXT NOT NULL,
                    feedback TEXT,
                    feedback_timestamp TEXT
                )
            """)
    # Additive lifecycle migration; old prediction rows and IDs are retained.
    from mlops.data.lifecycle import initialize_schema
    initialize_schema(target)


def log_prediction(url, prediction, confidence, model_version):
    timestamp = datetime.now(timezone.utc).isoformat()
    with get_connection() as conn:
        if conn.postgres:
            # RETURNING avoids relying on driver-specific lastrowid behavior.
            cur = conn.execute(
                """INSERT INTO predictions
                (timestamp, url, prediction, confidence, model_version)
                VALUES (?, ?, ?, ?, ?) RETURNING id""",
                (timestamp, url, prediction, confidence, model_version),
            )
            return cur.fetchone()["id"]
        cur = conn.execute(
            """INSERT INTO predictions
            (timestamp, url, prediction, confidence, model_version)
            VALUES (?, ?, ?, ?, ?)""",
            (timestamp, url, prediction, confidence, model_version),
        )
        return cur.lastrowid


def add_feedback(prediction_id, actual_label):
    # API feedback is only a user claim; it enters pending verification.
    from mlops.data.lifecycle import record_feedback
    return record_feedback(prediction_id, actual_label, get_database_target())


def get_predictions(limit=100):
    limit = max(1, min(int(limit), 1000))
    with get_connection() as conn:
        rows = conn.execute(
            """SELECT id, timestamp, url, prediction, confidence,
            model_version, feedback, feedback_timestamp
            FROM predictions ORDER BY id DESC LIMIT ?""",
            (limit,),
        ).fetchall()
    return [dict(zip(row.keys(), row)) for row in rows]
